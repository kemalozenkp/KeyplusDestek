import { readFileSync, writeFileSync, existsSync, realpathSync } from 'node:fs';
import { resolve, join, relative, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import { execFileSync } from 'node:child_process';
import { argumentsFor, readConfig, validateConfig } from './config.mjs';
import { uiPatches } from './ui-patches.mjs';

const project = JSON.parse(readFileSync(new URL('../project.json', import.meta.url), 'utf8'));
const normalize = text => text.replace(/\r\n/g, '\n');
const git = (directory, ...args) => execFileSync('git', ['-C', directory, ...args], {
  encoding: 'utf8', stdio: ['ignore', 'pipe', 'pipe'], maxBuffer: 8 * 1024 * 1024,
});

function replaceOnce(text, from, to, file) {
  const parts = text.split(from);
  if (parts.length !== 2) throw new Error(`${file}: beklenen kaynak bölümü tekil değil; dosya değiştirilmedi.`);
  return parts.join(to);
}

export function clientModule(input) {
  const config = validateConfig(input);
  const unattended = config.accessMode === 'unattended';
  const entries = {
    'custom-rendezvous-server': `${config.serverHost}:21116`,
    'relay-server': `${config.serverHost}:21117`,
    key: config.publicKey,
    'api-server': '',
    'enable-check-update': 'N',
    'allow-auto-update': 'N',
    'enable-terminal': 'N',
    'enable-tunnel': 'N',
  };
  const insertions = Object.entries(entries).map(([key, value]) =>
    `        settings.insert(${JSON.stringify(key)}.into(), ${JSON.stringify(value)}.into());`).join('\n');
  const accessDefaults = {
    'approve-mode': unattended ? 'password' : 'click',
    'verification-method': unattended ? 'use-permanent-password' : 'use-temporary-password',
    'allow-only-conn-window-open': unattended ? 'N' : 'Y',
  };
  const defaults = Object.entries(accessDefaults).map(([key, value]) =>
    `        defaults.insert(${JSON.stringify(key)}.into(), ${JSON.stringify(value)}.into());`).join('\n');
  return `// Keyplus Destek: generated by the independent source preparation tool.\n\
use hbb_common::config;\n\
use std::sync::Once;\n\
\n\
pub fn init() {\n\
    static INIT: Once = Once::new();\n\
    INIT.call_once(|| {\n\
        let mut settings = config::OVERWRITE_SETTINGS.write().unwrap();\n\
${insertions}\n\
        drop(settings);\n\
        let mut defaults = config::DEFAULT_SETTINGS.write().unwrap();\n\
${defaults}\n\
        drop(defaults);\n\
        let mut local = config::DEFAULT_LOCAL_SETTINGS.write().unwrap();\n\
        local.insert("lang".into(), "tr".into());\n\
        drop(local);\n\
        let mut hard = config::HARD_SETTINGS.write().unwrap();\n\
        hard.insert("disable-account".into(), "Y".into());\n\
        hard.insert("disable-ab".into(), "Y".into());\n\
        hard.insert("disable-installation".into(), "N".into());\n\
    });\n\
}\n`;
}

export function prepare(sourceDirectory, input, { check = false, runtimeConfig = false } = {}) {
  const config = runtimeConfig ? { serverHost: '127.0.0.1', publicKey: '' } : validateConfig(input);
  const source = realpathSync(sourceDirectory);
  const sourceRoot = realpathSync(git(source, 'rev-parse', '--show-toplevel').trim());
  if (sourceRoot !== source) throw new Error('Kaynak yolu RustDesk deposunun kökü olmalıdır.');
  const common = join(source, 'libs', 'hbb_common');
  for (const [directory, commit] of [[source, project.upstream.commit], [common, project.upstream.commonCommit]]) {
    if (git(directory, 'rev-parse', 'HEAD').trim() !== commit) {
      throw new Error(`${directory}: sabitlenmiş kaynak sürümüyle eşleşmiyor.`);
    }
  }
  const modifications = [];
  function patch(file, transform, directory = source) {
    const target = join(directory, ...file.split('/'));
    const actual = realpathSync(target);
    const inside = relative(source, actual);
    if (inside.startsWith('..') || resolve(source, inside) !== actual) {
      throw new Error(`${file}: kaynak dizini dışına çıkan dosya reddedildi.`);
    }
    const original = normalize(git(directory, 'show', `HEAD:${file}`));
    const updated = transform(original);
    const current = normalize(readFileSync(target, 'utf8'));
    if (current !== original && current !== updated) {
      throw new Error(`${file}: mevcut yerel değişiklik korunuyor; hazırlık durduruldu.`);
    }
    modifications.push({ target, content: updated, changed: current !== updated });
  }
  patch('src/lib.rs', original => `#[cfg(windows)]\nmod keyplus;\n#[cfg(windows)]\nmod keyplus_window;\n#[cfg(windows)]\nmod keyplus_health;\n#[cfg(windows)]\nmod keyplus_startup;\n${original}`);
  patch('src/common.rs', original => replaceOnce(original,
    'pub fn global_init() -> bool {',
    runtimeConfig
      ? 'pub fn global_init() -> bool {\n    #[cfg(windows)]\n    if !crate::keyplus::init() {\n        return false;\n    }'
      : 'pub fn global_init() -> bool {\n    #[cfg(windows)]\n    crate::keyplus::init();', 'src/common.rs'));
  patch('src/server/connection.rs', original => replaceOnce(original,
    '            if !crate::check_process("", !crate::platform::is_root()) {',
    '            #[cfg(all(windows, feature = "flutter"))]\n            let main_window_open = hbb_common::tokio::task::spawn_blocking(crate::keyplus_window::is_open).await.unwrap_or_else(|error| {\n                log::error!("Keyplus main-window check failed: {error}");\n                false\n            });\n            #[cfg(not(all(windows, feature = "flutter")))]\n            let main_window_open = crate::check_process("", !crate::platform::is_root());\n            if !main_window_open {', 'src/server/connection.rs'));
  patch('src/ipc/auth.rs', original => replaceOnce(original,
      '    #[cfg(target_os = "macos")]\n    if macos_service_ipc_allows_gui_and_service_binaries(&peer_exe, &current_exe, postfix) {',
      '    // DSK2697028: keep IPC identity checks without requiring an EXE name/directory.\n    #[cfg(windows)]\n    if postfix.is_empty() && crate::keyplus_window::same_application(peer_pid, &peer_exe)? {\n        return Ok(());\n    }\n    #[cfg(target_os = "macos")]\n    if macos_service_ipc_allows_gui_and_service_binaries(&peer_exe, &current_exe, postfix) {', 'src/ipc/auth.rs'));
  patch('src/config.rs', original => {
    let updated = replaceOnce(original,
      'RwLock::new("RustDesk".to_owned())',
      'RwLock::new("KeyplusDestek".to_owned())', 'hbb_common/config.rs');
    // Keep the first pilot's device ID, encrypted password and local settings.
    // The installer/IPC identifier is independent of the existing profile path.
    updated = replaceOnce(updated,
      'let name = format!("{}{}", *APP_NAME.read().unwrap(), suffix);',
      'let app_name = APP_NAME.read().unwrap().clone();\n        let config_name = if cfg!(windows) && app_name == "KeyplusDestek" { "Keyplus Destek" } else { app_name.as_str() };\n        let name = format!("{}{}", config_name, suffix);', 'hbb_common/config.rs');
    updated = replaceOnce(updated,
      'directories_next::ProjectDirs::from("", &org, &APP_NAME.read().unwrap())',
      'directories_next::ProjectDirs::from("", &org, {\n                    let app_name = APP_NAME.read().unwrap().clone();\n                    if cfg!(windows) && app_name == "KeyplusDestek" { "Keyplus Destek".to_owned() } else { app_name }\n                }.as_str())', 'hbb_common/config.rs');
    updated = replaceOnce(updated,
      'pub const RENDEZVOUS_SERVERS: &[&str] = &["rs-ny.rustdesk.com"];',
      `pub const RENDEZVOUS_SERVERS: &[&str] = &[${JSON.stringify(config.serverHost)}];`, 'hbb_common/config.rs');
    const line = updated.match(/^pub const RS_PUB_KEY: &str = "[^"\n]+";$/m)?.[0];
    if (!line) throw new Error('hbb_common/config.rs: açık anahtar sabiti bulunamadı.');
    return replaceOnce(updated, line, `pub const RS_PUB_KEY: &str = ${JSON.stringify(config.publicKey)};`, 'hbb_common/config.rs');
  }, common);
  patch('src/platform/mod.rs', original => `${original}\n\
#[cfg(all(test, windows))]\n\
mod keyplus_install_tests {\n\
    #[test]\n\
    fn branded_name_passes_the_real_installer_guard() {\n\
        let name = crate::get_app_name();\n\
        assert_eq!(name, "KeyplusDestek");\n\
        super::validate_install_app_name(&name).unwrap();\n\
        assert!(super::validate_install_app_name("Keyplus Destek").is_err());\n\
    }\n\
}\n`);
  patch('flutter/lib/common.dart', original => {
    let updated = "import 'desktop/pages/keyplus_text.dart';\n" + original;
    updated = replaceOnce(updated, 'String translate(String name) {',
      "String translate(String name) {\n  if (isWindows && keyplusTurkish.containsKey(name)) {\n    final language = bind.mainGetLocalOption(key: 'lang');\n    if (language == 'tr' || (language.isEmpty && localeName.startsWith('tr'))) return keyplusTurkish[name]!;\n  }", 'flutter/common.dart product terminology');
    for (const [from, to] of [
      ['static const Color grayBg = Color(0xFFEFEFF2);', 'static const Color grayBg = Color(0xFFF2F5F5);'],
      ['static const Color accent = Color(0xFF0071FF);', 'static const Color accent = Color(0xFFDF192A);'],
      ['static const Color accent50 = Color(0x770071FF);', 'static const Color accent50 = Color(0x77DF192A);'],
      ['static const Color accent80 = Color(0xAA0071FF);', 'static const Color accent80 = Color(0xAADF192A);'],
      ['static const Color idColor = Color(0xFF00B6F0);', 'static const Color idColor = Color(0xFF102B3B);'],
      ['static const Color button = Color(0xFF2C8CFF);', 'static const Color button = Color(0xFFDF192A);'],
      ['primary: Colors.blue, secondary: accent, background: grayBg', 'primary: accent, secondary: accent, background: grayBg'],
    ]) updated = replaceOnce(updated, from, to, 'flutter/common.dart');
    const start = updated.indexOf('  static ThemeData lightTheme = ThemeData(');
    const dark = updated.indexOf('  static ThemeData darkTheme = ThemeData(');
    if (start < 0 || dark < start) throw new Error('Flutter tema sınırları bulunamadı.');
    const lightTheme = updated.slice(start, dark).replaceAll('Colors.black87', 'Color(0xFF102B3B)')
      .replace('    useMaterial3: false,', "    useMaterial3: false,\n    fontFamily: 'Segoe UI',");
    // Restrict edits to the dark ThemeData expression, not session/status colors.
    const darkEnd = updated.indexOf('\n  static ', dark + 12);
    if (darkEnd < dark) throw new Error('Flutter koyu tema sonu bulunamadı.');
    const darkTheme = updated.slice(dark, darkEnd)
      .replace('    useMaterial3: false,', "    useMaterial3: false,\n    fontFamily: 'Segoe UI',")
      .replaceAll('Color(0xFF18191E)', 'Color(0xFF102B3B)')
      .replaceAll('Color(0xFF24252B)', 'Color(0xFF142D3C)')
      .replaceAll('Color(0xFF121212)', 'Color(0xFF0C202C)')
      .replace('primary: Colors.blue,', 'primary: Color(0xFFFF7785),')
      .replace('secondary: accent,', 'secondary: Color(0xFFFF7785),')
      .replace('color: accent80,', 'color: Color(0xFFFF7785),');
    updated = updated.slice(0, start) + lightTheme + darkTheme + updated.slice(darkEnd);
    return replaceOnce(updated,
      'constraints: BoxConstraints(maxWidth: 300, maxHeight: 60),\n            child: image,',
      'constraints: BoxConstraints(maxWidth: 300, maxHeight: 60),\n            color: Theme.of(context).brightness == Brightness.dark ? Colors.white : null,\n            child: image,', 'flutter/common.dart corporate logo contrast');
  });
  uiPatches(patch, replaceOnce);
  patch('flutter/windows/runner/Runner.rc', original => {
    let updated = replaceOnce(original, '"FileDescription", "RustDesk Remote Desktop"',
      '"FileDescription", "Keyplus Destek Remote Support"', 'Runner.rc');
    return replaceOnce(updated, '"ProductName", "RustDesk"', '"ProductName", "Keyplus Destek"', 'Runner.rc');
  });
  const generated = join(source, 'src', 'keyplus.rs');
  const content = runtimeConfig
    ? normalize(readFileSync(new URL('../templates/keyplus_runtime.rs', import.meta.url), 'utf8'))
    : clientModule(config);
  if (existsSync(generated)) {
    const actual = realpathSync(generated);
    if (actual !== generated || normalize(readFileSync(generated, 'utf8')) !== content) {
      throw new Error('src/keyplus.rs zaten var ve içeriği farklı; dosya korunuyor.');
    }
  }
  modifications.push({ target: generated, content, changed: !existsSync(generated) });
  const windowTarget = join(source, 'src', 'keyplus_window.rs');
  const windowContent = normalize(readFileSync(new URL('../templates/keyplus_window.rs', import.meta.url), 'utf8'));
  if (existsSync(windowTarget) && (realpathSync(windowTarget) !== windowTarget
    || normalize(readFileSync(windowTarget, 'utf8')) !== windowContent)) {
    throw new Error('src/keyplus_window.rs zaten var ve içeriği farklı; dosya korunuyor.');
  }
  modifications.push({ target: windowTarget, content: windowContent, changed: !existsSync(windowTarget) });
  for (const [template, file] of [
    ['keyplus_health.rs', 'src/keyplus_health.rs'],
    ['keyplus_startup.rs', 'src/keyplus_startup.rs'],
    ['keyplus_home.dart', 'flutter/lib/desktop/pages/keyplus_home.dart'],
    ['keyplus_text.dart', 'flutter/lib/desktop/pages/keyplus_text.dart'],
    ['keyplus_layout.dart', 'flutter/lib/desktop/pages/keyplus_layout.dart'],
    ['keyplus_access.dart', 'flutter/lib/desktop/pages/keyplus_access.dart'],
    ['keyplus_ui_test.dart', 'flutter/test/keyplus_ui_test.dart'],
  ]) {
    const target = join(source, ...file.split('/'));
    const content = normalize(readFileSync(new URL(`../templates/${template}`, import.meta.url), 'utf8'));
    const parent = realpathSync(dirname(target));
    const inside = relative(source, parent);
    if (inside.startsWith('..') || resolve(source, inside) !== parent) {
      throw new Error(`${file}: kaynak dizini dışına çıkan klasör reddedildi.`);
    }
    if (existsSync(target) && (realpathSync(target) !== target || normalize(readFileSync(target, 'utf8')) !== content)) {
      throw new Error(`${file}: mevcut üretilmiş dosya farklı; dosya korunuyor.`);
    }
    modifications.push({ target, content, changed: !existsSync(target) });
  }
  // All targets have been validated before the first write.
  if (!check) {
    for (const modification of modifications) {
      if (modification.changed) writeFileSync(modification.target, modification.content, 'utf8');
    }
  }
  return modifications.map(({ target, changed }) => ({ file: relative(source, target), changed }));
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  try {
    const args = argumentsFor(process.argv.slice(2), ['--source', '--config', '--check', '--runtime-config']);
    if (!args['--source'] || (!args['--config'] && !args['--runtime-config']) || (args['--config'] && args['--runtime-config'])) {
      throw new Error('Kullanım: node scripts/prepare.mjs --source <rustdesk-kökü> (--config <json> | --runtime-config) [--check]');
    }
    const result = prepare(args['--source'], args['--config'] ? readConfig(args['--config']) : null,
      { check: args['--check'], runtimeConfig: args['--runtime-config'] });
    console.log(JSON.stringify({ mode: args['--check'] ? 'kontrol' : 'uygulandı', files: result }, null, 2));
  } catch (error) {
    console.error(`Keyplus Destek kaynak hazırlığı başarısız: ${error.message}`);
    process.exitCode = 1;
  }
}
